"""Per-user target database connections. app_db remains on the existing MySQL connector.

Connection URLs are encrypted at rest and are never returned by API responses. SQLAlchemy
provides common connection/introspection APIs; users should supply read-only DB credentials.
"""
from __future__ import annotations

import hashlib
import ipaddress
import socket
from dataclasses import dataclass
from pathlib import Path

from cryptography.fernet import Fernet, InvalidToken
from sqlalchemy import create_engine, inspect, text
from sqlalchemy.engine import Engine, URL, make_url
from sqlalchemy.exc import SQLAlchemyError

from . import config
from .db import get_conn


class TargetDatabaseError(ValueError):
    """Safe-to-display target database configuration or connection error."""


@dataclass(frozen=True)
class TargetDatabase:
    id: int | None
    user_id: int | None
    name: str
    dialect: str
    engine: Engine
    is_legacy: bool = False


def _fernet() -> Fernet:
    key = config.CONNECTION_ENCRYPTION_KEY.strip()
    if not key:
        raise TargetDatabaseError(
            "Database connections are not configured yet. Set CONNECTION_ENCRYPTION_KEY in .env "
            "using a Fernet key generated by the setup instructions, then restart the server."
        )
    try:
        return Fernet(key.encode("ascii"))
    except Exception as exc:
        raise TargetDatabaseError("CONNECTION_ENCRYPTION_KEY is invalid. Generate a valid Fernet key.") from exc


def encrypt_url(database_url: str) -> str:
    return _fernet().encrypt(database_url.encode("utf-8")).decode("ascii")


def decrypt_url(encrypted: str) -> str:
    try:
        return _fernet().decrypt(encrypted.encode("ascii")).decode("utf-8")
    except (InvalidToken, ValueError, UnicodeError) as exc:
        raise TargetDatabaseError("Stored database credentials could not be decrypted. Check CONNECTION_ENCRYPTION_KEY.") from exc


def validate_database_url(database_url: str) -> URL:
    raw = (database_url or "").strip()
    if not raw or len(raw) > 4096:
        raise TargetDatabaseError("Enter a valid database URL (maximum 4096 characters).")
    try:
        url = make_url(raw)
    except Exception as exc:
        raise TargetDatabaseError("The database URL format is invalid.") from exc
    if not url.drivername or not url.drivername.split("+")[0]:
        raise TargetDatabaseError("The database URL must include a SQLAlchemy dialect.")
    # Normalize common short URLs to drivers installed by this project.
    defaults = {"mysql": "mysql+mysqlconnector", "postgresql": "postgresql+psycopg",
                "mssql": "mssql+pyodbc", "oracle": "oracle+oracledb", "mariadb": "mysql+mysqlconnector"}
    if url.drivername in defaults:
        url = url.set(drivername=defaults[url.drivername])
    dialect = url.get_backend_name().lower()
    if dialect in {"mysql", "mariadb", "postgresql", "mssql", "oracle"} and not url.host:
        raise TargetDatabaseError("A host is required for this database type.")
    if dialect == "sqlite" and not url.database:
        raise TargetDatabaseError("A SQLite URL must include a database file path or :memory:.")
    if dialect == "sqlite" and url.database == ":memory:":
        raise TargetDatabaseError("Use a file-backed SQLite database; in-memory databases do not persist across requests.")
    if dialect == "sqlite" and url.database not in (None, ":memory:"):
        # SQLite opens files on the application server, not on the user's computer. Keep it
        # inside a dedicated directory to prevent URLs from reading arbitrary server files.
        allowed_root = Path(config.SQLITE_ALLOWED_ROOT).expanduser().resolve()
        allowed_root.mkdir(parents=True, exist_ok=True)
        supplied = Path(url.database).expanduser()
        candidate = (allowed_root / supplied).resolve() if not supplied.is_absolute() else supplied.resolve()
        try:
            candidate.relative_to(allowed_root)
        except ValueError as exc:
            raise TargetDatabaseError(f"SQLite files must be inside {allowed_root}.") from exc
        url = url.set(database=str(candidate))
    # Block the common cloud metadata endpoints. Deployment-level egress controls are still required.
    host = (url.host or "").rstrip(".").lower()
    if host in {"metadata.google.internal", "metadata", "instance-data.ec2.internal"}:
        raise TargetDatabaseError("Connections to cloud metadata endpoints are not permitted.")
    if host:
        try:
            ip = ipaddress.ip_address(host.strip("[]"))
            if ip == ipaddress.ip_address("") or ip.is_link_local:
                raise TargetDatabaseError("Connections to link-local metadata addresses are not permitted.")
        except ValueError:
            # A hostname may resolve to a metadata address; check current DNS answers too.
            try:
                for answer in socket.getaddrinfo(host, url.port or 0, type=socket.SOCK_STREAM):
                    ip = ipaddress.ip_address(answer[4][0].split("%", 1)[0])
                    if ip == ipaddress.ip_address("") or ip.is_link_local:
                        raise TargetDatabaseError("Connections to link-local metadata addresses are not permitted.")
            except socket.gaierror:
                pass  # create_engine/test-connection will report a safe connection error.
    return url


def _engine_options(url: URL) -> dict:
    options = {"pool_pre_ping": True, "pool_recycle": 1800, "future": True}
    if url.get_backend_name() == "sqlite":
        options.update(connect_args={"timeout": max(1, config.QUERY_TIMEOUT_SEC)})
        if url.database == ":memory:":
            options.update(pool_size=1, max_overflow=0)
    else:
        args = {}
        if url.get_backend_name() == "postgresql":
            args = {"connect_timeout": 10}
        elif url.get_backend_name() in {"mysql", "mariadb"}:
            args = {"connection_timeout": 10} if url.drivername.endswith("mysqlconnector") else {"connect_timeout": 10}
        options.update(pool_size=3, max_overflow=2, pool_timeout=10, connect_args=args)
    return options


def build_engine(database_url: str) -> Engine:
    url = validate_database_url(database_url)
    try:
        return create_engine(url, **_engine_options(url))
    except Exception as exc:
        # Do not include the URL: it can contain passwords.
        raise TargetDatabaseError(f"Could not initialize the {url.get_backend_name()} driver. Install its SQLAlchemy driver.") from exc


def test_database_url(database_url: str) -> dict:
    engine = build_engine(database_url)
    try:
        with engine.connect() as conn:
            conn.execute(text("SELECT 1"))
        return {"ok": True, "dialect": engine.dialect.name, "message": "Connection successful."}
    except Exception as exc:
        raise TargetDatabaseError(f"Connection failed: {_safe_error(exc)}") from exc
    finally:
        engine.dispose()


def _safe_error(exc: Exception) -> str:
    # Avoid returning URLs/credentials that some DB drivers include in exceptions.
    message = str(exc).splitlines()[0][:240]
    return message if "@" not in message else "The database rejected the connection or is unreachable."


def _legacy_url() -> str:
    from sqlalchemy.engine import URL
    return URL.create(
        "mysql+mysqlconnector", username=config.TARGET_DB_USER, password=config.TARGET_DB_PASSWORD,
        host=config.TARGET_DB_HOST, port=config.TARGET_DB_PORT, database=config.TARGET_DB_NAME,
        query={"charset": "utf8mb4"},
    ).render_as_string(hide_password=False)


def _connection_row(user_id: int, connection_id: int | None):
    if connection_id == 0:
        return {"id": 0, "user_id": user_id, "name": config.TARGET_DB_NAME, "encrypted_url": None, "dialect": "mysql", "is_default": False, "_legacy": True}
    with get_conn() as conn:
        if connection_id is not None:
            row = conn.one(
                "SELECT id,user_id,name,encrypted_url,dialect,is_default FROM database_connections WHERE id=%s AND user_id=%s",
                (connection_id, user_id),
            )
            if not row:
                raise TargetDatabaseError("Database connection not found.")
            return row
        row = conn.one(
            "SELECT id,user_id,name,encrypted_url,dialect,is_default FROM database_connections WHERE user_id=%s AND is_default=1 ORDER BY id LIMIT 1",
            (user_id,),
        )
        if row:
            return row
        count = conn.one("SELECT COUNT(*) AS n FROM database_connections WHERE user_id=%s", (user_id,))
        if count and count["n"]:
            raise TargetDatabaseError("Select one of your database connections before asking a question.")
    # Backwards-compatible fallback while users migrate from the original single shop_db target.
    return {"id": None, "user_id": user_id, "name": config.TARGET_DB_NAME,
            "encrypted_url": None, "dialect": "mysql", "is_default": True, "_legacy": True}


_engine_cache: dict[tuple[int, str], Engine] = {}


def resolve_connection_id(user_id: int, connection_id: int | None = None) -> int | None:
    """Resolve and authorize a connection selection; None means legacy shop_db fallback."""
    row = _connection_row(user_id, connection_id)
    return 0 if row.get("_legacy") else int(row["id"])


def get_target_database(user_id: int, connection_id: int | None = None) -> TargetDatabase:
    row = _connection_row(user_id, connection_id)
    if row.get("_legacy"):
        url = _legacy_url()
    else:
        url = decrypt_url(row["encrypted_url"])
    key = (int(row["id"] or 0), hashlib.sha256(url.encode()).hexdigest())
    engine = _engine_cache.get(key)
    if engine is None:
        engine = build_engine(url)
        _engine_cache[key] = engine
    return TargetDatabase(row["id"], user_id, row["name"], engine.dialect.name, engine, bool(row.get("_legacy")))


def create_user_connection(user_id: int, name: str, database_url: str, make_default: bool = False) -> dict:
    name = (name or "").strip()
    if not name or len(name) > 80:
        raise TargetDatabaseError("Connection name must be between 1 and 80 characters.")
    # Test before persisting credentials, and never return the URL to the browser.
    test = test_database_url(database_url)
    encrypted = encrypt_url(database_url.strip())
    with get_conn() as conn:
        if make_default:
            conn.execute("UPDATE database_connections SET is_default=0 WHERE user_id=%s", (user_id,))
        existing = conn.one("SELECT COUNT(*) AS n FROM database_connections WHERE user_id=%s", (user_id,))
        is_default = bool(make_default or not (existing and existing["n"]))
        cid = conn.insert(
            "INSERT INTO database_connections (user_id,name,encrypted_url,dialect,is_default) VALUES (%s,%s,%s,%s,%s)",
            (user_id, name, encrypted, test["dialect"], int(is_default)),
        )
    return {"id": cid, "name": name, "dialect": test["dialect"], "is_default": is_default}


def list_user_connections(user_id: int) -> list[dict]:
    with get_conn() as conn:
        return conn.all("SELECT id,name,dialect,is_default,created_at FROM database_connections WHERE user_id=%s ORDER BY is_default DESC,id", (user_id,))


def set_default_connection(user_id: int, connection_id: int) -> None:
    with get_conn() as conn:
        row = conn.one("SELECT id FROM database_connections WHERE id=%s AND user_id=%s", (connection_id, user_id))
        if not row:
            raise TargetDatabaseError("Database connection not found.")
        conn.execute("UPDATE database_connections SET is_default=0 WHERE user_id=%s", (user_id,))
        conn.execute("UPDATE database_connections SET is_default=1 WHERE id=%s AND user_id=%s", (connection_id, user_id))


def delete_user_connection(user_id: int, connection_id: int) -> None:
    with get_conn() as conn:
        row = conn.one("SELECT id,is_default FROM database_connections WHERE id=%s AND user_id=%s", (connection_id, user_id))
        if not row:
            raise TargetDatabaseError("Database connection not found.")
        conn.execute("DELETE FROM database_connections WHERE id=%s AND user_id=%s", (connection_id, user_id))
        if row["is_default"]:
            nxt = conn.one("SELECT id FROM database_connections WHERE user_id=%s ORDER BY id LIMIT 1", (user_id,))
            if nxt:
                conn.execute("UPDATE database_connections SET is_default=1 WHERE id=%s", (nxt["id"],))
    for key, engine in list(_engine_cache.items()):
        if key[0] == connection_id:
            engine.dispose()
            _engine_cache.pop(key, None)


def inspect_schema(target: TargetDatabase, sample_rows: int = 0) -> tuple[dict, list, dict]:
    """Return (tables, foreign keys, sample rows) using SQLAlchemy's dialect-aware inspector."""
    inspector = inspect(target.engine)
    tables: dict[str, list[dict]] = {}
    foreign_keys: list[dict] = []
    samples: dict[str, list[dict]] = {}
    try:
        names = inspector.get_table_names()
        for table_name in names:
            columns = inspector.get_columns(table_name)
            pk = set((inspector.get_pk_constraint(table_name) or {}).get("constrained_columns") or [])
            tables[table_name] = []
            for col in columns:
                tables[table_name].append({
                    "c": col["name"], "ty": str(col.get("type", "unknown")),
                    "nl": "YES" if col.get("nullable", True) else "NO",
                    "k": "PRI" if col["name"] in pk else "",
                })
            for fk in inspector.get_foreign_keys(table_name):
                for local, remote in zip(fk.get("constrained_columns") or [], fk.get("referred_columns") or []):
                    foreign_keys.append({"t": table_name, "c": local, "rt": fk.get("referred_table", "?"), "rc": remote})
            if sample_rows > 0:
                from sqlalchemy import MetaData, Table, select
                meta = MetaData()
                tbl = Table(table_name, meta, autoload_with=target.engine)
                with target.engine.connect() as conn:
                    rows = conn.execute(select(tbl).limit(int(sample_rows))).mappings().all()
                samples[table_name] = [dict(r) for r in rows]
        return tables, foreign_keys, samples
    except Exception as exc:
        raise TargetDatabaseError(f"Could not inspect the selected database schema: {_safe_error(exc)}") from exc
